-- Application schema for the DevPath backend.
-- Run this once in the new Supabase project's SQL Editor.

create table if not exists public.users (
  id integer generated by default as identity primary key,
  github_id varchar(64) not null unique,
  username varchar(64) not null unique,
  avatar_url text not null,
  display_name varchar(120), bio text, student_id varchar(64),
  program varchar(64), year_level varchar(32), career_interest varchar(160),
  preferred_learning_style varchar(80), target_role varchar(160),
  target_certifications jsonb default '[]'::jsonb, github_token text,
  freecodecamp_username varchar(120), bonus_xp integer default 0,
  last_cert_sync_at timestamptz, role varchar(20) default 'student',
  last_seen timestamptz, is_verified boolean default false,
  verified_at timestamptz, created_at timestamptz default now()
);

create table if not exists public.admin_accounts (
  id integer generated by default as identity primary key,
  username varchar(64) not null unique,
  password_hash text not null, password_salt varchar(64) not null,
  role varchar(20) default 'admin', created_at timestamptz default now()
);

create table if not exists public.repos (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id),
  name varchar(200) not null, description text, language varchar(64),
  languages jsonb default '[]'::jsonb, language_bytes jsonb default '{}'::jsonb,
  stars integer default 0, topics jsonb default '[]'::jsonb,
  code_signals jsonb default '{}'::jsonb, last_push text,
  commit_count integer default 0
);

create table if not exists public.practice_dimensions (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id),
  label varchar(120) not null, confidence integer not null,
  evidence jsonb default '[]'::jsonb
);

create table if not exists public.career_suggestions (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id),
  title varchar(160) not null, confidence integer not null,
  reasoning text not null
);

create table if not exists public.badges (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id),
  label varchar(120) not null, description text not null,
  criteria text not null, rarity varchar(20) not null,
  achieved boolean default false, claimed boolean default false,
  constraint uq_badges_user_label unique (user_id, label)
);

create table if not exists public.portfolio_settings (
  id integer generated by default as identity primary key,
  user_id integer not null unique references public.users(id),
  theme varchar(32) default 'aurora', theme_light varchar(32) default 'aurora',
  theme_dark varchar(32) default 'aurora', section_order jsonb default '[]'::jsonb,
  show_sections jsonb default '{"badges": true, "repos": true, "preview_dark": false}'::jsonb,
  featured_repos jsonb default '[]'::jsonb, featured_badges jsonb default '[]'::jsonb,
  social_links jsonb default '{}'::jsonb, bio text, cover_image text,
  is_public boolean default true, learning_path_baseline jsonb default '[]'::jsonb,
  project_learning_path_baseline jsonb default '{}'::jsonb
);

create table if not exists public.admin_notes (
  id integer generated by default as identity primary key,
  admin_id integer not null references public.admin_accounts(id),
  student_id integer not null references public.users(id),
  note text not null, created_at timestamptz default now()
);

create table if not exists public.project_validations (
  id integer generated by default as identity primary key,
  admin_id integer not null references public.admin_accounts(id),
  student_id integer not null references public.users(id),
  repo_name varchar(200) not null, status varchar(20) default 'pending',
  comment text, created_at timestamptz default now()
);

create table if not exists public.portfolio_reviews (
  id integer generated by default as identity primary key,
  admin_id integer not null references public.admin_accounts(id),
  student_id integer not null references public.users(id),
  status varchar(30) default 'needs_work', summary text not null,
  created_at timestamptz default now()
);

create table if not exists public.activity_logs (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), event varchar(64) not null,
  meta jsonb default '{}'::jsonb, created_at timestamptz default now()
);

create table if not exists public.engagement_commits (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id),
  week_start timestamptz not null, commit_count integer default 0,
  created_at timestamptz default now()
);

create table if not exists public.learning_progress (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), learning_step text not null,
  status varchar(20) default 'todo', completed_at timestamptz,
  created_at timestamptz default now()
);

create table if not exists public.learning_paths (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), repo_name varchar(200) not null,
  path_level integer default 1 not null, status varchar(20) default 'active' not null,
  progress_percent integer default 0 not null, personalization_key varchar(128),
  source_profile jsonb default '{}'::jsonb, created_at timestamptz default now(),
  updated_at timestamptz default now(),
  constraint uq_learning_paths_user_repo_level unique (user_id, repo_name, path_level)
);

create table if not exists public.learning_path_stages (
  id integer generated by default as identity primary key,
  learning_path_id integer not null references public.learning_paths(id),
  stage_index integer not null, title varchar(255) not null, description text not null,
  stage_type varchar(30) default 'Skill' not null, tag varchar(120),
  difficulty varchar(30) default 'Beginner' not null, reward_xp integer default 0 not null,
  resources jsonb default '{}'::jsonb, evidence jsonb default '[]'::jsonb,
  status varchar(20) default 'todo' not null, created_at timestamptz default now(),
  updated_at timestamptz default now(),
  constraint uq_learning_path_stage_order unique (learning_path_id, stage_index)
);

create table if not exists public.stage_progress_updates (
  id integer generated by default as identity primary key,
  learning_path_stage_id integer not null references public.learning_path_stages(id),
  user_id integer not null references public.users(id), comment text,
  proof_items jsonb default '[]'::jsonb, review_status varchar(20) default 'pending' not null,
  admin_feedback text, created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.xp_history (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), week_start timestamptz not null,
  xp_gained integer default 0, created_at timestamptz default now()
);

create table if not exists public.login_activity (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), login_timestamp timestamptz not null,
  login_date varchar(10) not null, login_hour integer not null,
  ip_address varchar(64), device text, created_at timestamptz default now()
);

create table if not exists public.certificate_records (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), title varchar(255) not null,
  provider varchar(160) not null, proof_type varchar(40), certificate_url text not null,
  certificate_page_url text, student_note text, suggestion_track_id varchar(160),
  suggestion_module_url text, completion_locked boolean default false,
  completion_reward_xp integer, rewarded_at timestamptz, hidden_from_student boolean default false,
  status varchar(20) default 'pending', reviewer_id integer references public.admin_accounts(id),
  reviewer_note text, submitted_at timestamptz default now(), verified_at timestamptz
);

create table if not exists public.fcc_module_progress (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), module_key varchar(120) not null,
  module_title varchar(255) not null, status varchar(20) default 'not_started',
  progress_percent integer default 0, notes text, certificate_url text,
  completed_at timestamptz, created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.intervention_plans (
  id integer generated by default as identity primary key,
  student_id integer not null references public.users(id),
  admin_id integer not null references public.admin_accounts(id),
  title varchar(255) not null, action_plan text not null,
  priority varchar(20) default 'Medium', target_date varchar(20), status varchar(20) default 'open',
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create table if not exists public.daily_quest_claims (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), quest_key varchar(80) not null,
  quest_date varchar(10) not null, reward_xp integer default 0,
  claimed_at timestamptz default now()
);

create table if not exists public.weekly_challenge_claims (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), challenge_key varchar(80) not null,
  week_start varchar(10) not null, reward_xp integer default 0,
  claimed_at timestamptz default now()
);

create table if not exists public.recommendation_actions (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), dimension_key varchar(120),
  module_title varchar(255) not null, module_url text not null,
  action varchar(20) not null, rating integer, feedback text,
  created_at timestamptz default now()
);

create table if not exists public.sus_survey_responses (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), score integer not null,
  feedback text, created_at timestamptz default now()
);

create table if not exists public.student_goals (
  id integer generated by default as identity primary key,
  user_id integer not null references public.users(id), title varchar(255) not null,
  target_value integer, current_value integer default 0, unit varchar(64),
  status varchar(20) default 'active', target_date varchar(20), notes text,
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create index if not exists idx_repos_user_id on public.repos(user_id);
create index if not exists idx_practice_dimensions_user_id on public.practice_dimensions(user_id);
create index if not exists idx_career_suggestions_user_id on public.career_suggestions(user_id);
create index if not exists idx_activity_logs_user_id on public.activity_logs(user_id);
create index if not exists idx_learning_paths_user_id on public.learning_paths(user_id);
create index if not exists idx_learning_path_stages_path_id on public.learning_path_stages(learning_path_id);
create index if not exists idx_stage_progress_updates_user_id on public.stage_progress_updates(user_id);
create index if not exists idx_certificate_records_user_id on public.certificate_records(user_id);
create index if not exists idx_fcc_module_progress_user_id on public.fcc_module_progress(user_id);
create index if not exists idx_student_goals_user_id on public.student_goals(user_id);
